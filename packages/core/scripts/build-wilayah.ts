// Converts cahyadsn/wilayah's `db/wilayah.sql` (MIT, Kepmendagri codes) into the
// compact JSON files shipped in `data/` plus the generated `src/provinces.ts`.
//
// Optionally also cahyadsn/wilayah_kodepos's `db/wilayah_kodepos.sql` (MIT) for `data/kodepos.json`.
//
// Usage: node scripts/build-wilayah.ts <path/to/wilayah.sql> [path/to/wilayah_kodepos.sql]
import { readFileSync, writeFileSync } from 'node:fs';

const sqlPath = process.argv[2];
const kodeposPath = process.argv[3];
if (!sqlPath) {
  console.error('Usage: node scripts/build-wilayah.ts <path/to/wilayah.sql> [path/to/wilayah_kodepos.sql]');
  process.exit(1);
}

const sql = readFileSync(sqlPath, 'utf8');
const row = /\('([0-9.]+)','((?:[^'\\]|\\.|'')*)'\)/g;

const base: Record<string, string> = {};
const desa: Record<string, string> = {};
let count = 0;

for (const m of sql.matchAll(row)) {
  const code = m[1]!;
  const name = m[2]!.replace(/\\'/g, "'").replace(/''/g, "'").replace(/\s+/g, ' ').trim();
  const level = code.split('.').length;
  if (level === 4) desa[code] = name;
  else if (level <= 3) base[code] = name;
  else continue;
  count++;
}

const sortKeys = (o: Record<string, string>) =>
  Object.fromEntries(Object.entries(o).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));

const dataDir = new URL('../data/', import.meta.url);
writeFileSync(new URL('wilayah.json', dataDir), JSON.stringify(sortKeys(base)));
writeFileSync(new URL('desa.json', dataDir), JSON.stringify(sortKeys(desa)));

const provinces = Object.entries(sortKeys(base)).filter(([code]) => !code.includes('.'));
const ts = `// Generated by scripts/build-wilayah.ts from cahyadsn/wilayah (Kepmendagri). Do not edit.
export const PROVINCES: Readonly<Record<string, string>> = {
${provinces.map(([code, name]) => `  '${code}': ${JSON.stringify(name)},`).join('\n')}
};
`;
writeFileSync(new URL('../src/provinces.ts', import.meta.url), ts);

if (kodeposPath) {
  const kodepos: Record<string, string> = {};
  for (const m of readFileSync(kodeposPath, 'utf8').matchAll(/\('([0-9.]+)',\s*'(\d{5})'\)/g)) {
    if (desa[m[1]!]) kodepos[m[1]!] = m[2]!;
  }
  writeFileSync(new URL('kodepos.json', dataDir), JSON.stringify(sortKeys(kodepos)));
  const missing = Object.keys(desa).filter((c) => !kodepos[c]).length;
  console.log(`kodepos=${Object.keys(kodepos).length} desa tanpa kodepos=${missing}`);
}

const levels = [1, 2, 3].map((l) => Object.keys(base).filter((c) => c.split('.').length === l).length);
console.log(`rows=${count} provinsi=${levels[0]} kab/kota=${levels[1]} kecamatan=${levels[2]} desa/kelurahan=${Object.keys(desa).length}`);
